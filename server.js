async function settleTickets() {
  try {
    const pending = await Ticket.find({ status: 'pending', autoGenerated: true }).limit(30);
    let settled = 0;
    for (const ticket of pending) {
      try {
        let allFinished = true;
        let allWon = true;
        for (const leg of ticket.legs || []) {
          if (!leg.eventId) { allFinished = false; break; }
          const log = await PredictionLog.findOne({ eventId: leg.eventId }).lean();
          if (!log || !log.settledAt) { allFinished = false; break; }
          const expectedBtts = leg.pick === 'Yes';
          const actualBtts = log.btts;
          if (expectedBtts !== actualBtts) allWon = false;
        }
        if (!allFinished) continue;
        ticket.status = allWon ? 'won' : 'lost';
        ticket.resultNote = allWon ? `All ${ticket.legs.length} legs hit` : `Leg(s) missed`;
        ticket.settledAt = new Date();
        await ticket.save();
        settled++;
        console.log(`[Tickets] Auto-settled: "${ticket.title}" → ${ticket.status}`);
      } catch (e) { /* silent */ }
    }
    return { settled };
  } catch (e) { return { settled: 0 }; }
}

