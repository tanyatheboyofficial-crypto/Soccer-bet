// ═══════════════════════════════════════════════════════════
// META-LEARNER + CALIBRATION
// ═══════════════════════════════════════════════════════════
function trainLogistic(samples, featureNames, opts = {}) {
  const lr = opts.lr || 0.05;
  const epochs = opts.epochs || 300;
  const l2 = opts.l2 || 0.01;
  const means = {}, stds = {};
  for (const f of featureNames) {
    const vals = samples.map(s => Number(s.features[f] ?? 0));
    const m = vals.reduce((a, v) => a + v, 0) / vals.length;
    const sd = Math.sqrt(vals.reduce((a, v) => a + Math.pow(v - m, 2), 0) / vals.length) || 1;
    means[f] = m; stds[f] = sd;
  }
  const weights = { intercept: 0 };
  for (const f of featureNames) weights[f] = 0;
  for (let e = 0; e < epochs; e++) {
    const grad = { intercept: 0 };
    for (const f of featureNames) grad[f] = 0;
    for (const s of samples) {
      let z = weights.intercept;
      for (const f of featureNames) z += weights[f] * ((Number(s.features[f] ?? 0) - means[f]) / stds[f]);
      const p = 1 / (1 + Math.exp(-z));
      const err = p - (s.correct ? 1 : 0);
      grad.intercept += err;
      for (const f of featureNames) grad[f] += err * ((Number(s.features[f] ?? 0) - means[f]) / stds[f]);
    }
    weights.intercept -= lr * grad.intercept / samples.length;
    for (const f of featureNames) weights[f] -= lr * (grad[f] / samples.length + l2 * weights[f]);
  }
  return { weights, means, stds };
}

async function trainMetaLearner(market) {
  const snaps = await FeatureSnapshot.find({ market, settledAt: { $ne: null } }).lean();
  if (snaps.length < ENV.META_MIN_SAMPLES) {
    if (snaps.length > 0) console.log(`[Learning] Meta ${market}: only ${snaps.length}/${ENV.META_MIN_SAMPLES} samples, skipping`);
    return;
  }
  const featureNames = Object.keys(snaps[0].features || {});
  if (!featureNames.length) return;
  const { weights, means, stds } = trainLogistic(snaps, featureNames);
  let correct = 0;
  for (const s of snaps) {
    let z = weights.intercept;
    for (const f of featureNames) z += weights[f] * ((Number(s.features[f] ?? 0) - means[f]) / stds[f]);
    const p = 1 / (1 + Math.exp(-z));
    if ((p >= 0.5) === s.correct) correct++;
  }
  const accuracy = correct / snaps.length;
  await MetaLearner.updateOne(
    { market },
    { $set: { weights: { ...weights, _means: means, _stds: stds }, samples: snaps.length, accuracy: +accuracy.toFixed(4), lastTrained: new Date() } },
    { upsert: true }
  );
  META_AT = 0;
  console.log(`[Learning] Meta-learner ${market}: acc=${(accuracy * 100).toFixed(1)}% n=${snaps.length}`);
}

async function metaPredictCached(market, features) {
  const ml = await getCachedMeta(market);
  if (!ml || ml.samples < ENV.META_MIN_SAMPLES) return null;
  if (ml.accuracy < ENV.META_MIN_ACCURACY) return null;
  const { weights } = ml;
  const means = weights._means || {};
  const stds = weights._stds || {};
  let z = weights.intercept || 0;
  for (const [f, v] of Object.entries(features)) {
    if (weights[f] === undefined) continue;
    z += weights[f] * ((Number(v) - (means[f] ?? 0)) / (stds[f] ?? 1));
  }
  return 1 / (1 + Math.exp(-z));
}

async function calibrateProbCached(market, rawProb) {
  const cal = await getCachedCalibration(market);
  if (!cal || !cal.buckets?.length) return rawProb;
  for (const b of cal.buckets) {
    if (rawProb >= b.rawMin && rawProb < b.rawMax) return b.calibratedProb;
  }
  return rawProb;
}

async function recalibrateMarket(market) {
  const snaps = await FeatureSnapshot.find({ market, settledAt: { $ne: null } }).lean();
  if (snaps.length < 50) return;
  const buckets = [];
  for (let i = 0; i < 5; i++) {
    const lo = 0.5 + i * 0.1, hi = lo + 0.1;
    const inB = snaps.filter(s => s.rawProb >= lo && s.rawProb < hi);
    if (!inB.length) continue;
    const predicted = inB.reduce((a, s) => a + s.rawProb, 0) / inB.length;
    const actual = inB.filter(s => s.correct).length / inB.length;
    const calibrated = actual * 0.7 + predicted * 0.3;
    buckets.push({
      rawMin: lo, rawMax: hi,
      predictedCount: inB.length,
      actualHits: inB.filter(s => s.correct).length,
      calibratedProb: +calibrated.toFixed(4),
    });
  }
  const brier = snaps.reduce((a, s) => a + Math.pow(s.rawProb - (s.correct ? 1 : 0), 2), 0) / snaps.length;
  await Calibration.updateOne(
    { market },
    { $set: { buckets, totalSamples: snaps.length, brierScore: +brier.toFixed(4), lastUpdated: new Date() } },
    { upsert: true }
  );
  CALIB_AT = 0;
}

async function updateRulePerformance() {
  const settled = await PredictionLog.find({ settledAt: { $ne: null } }).lean();
  if (settled.length < 30) return;
  const baseBtts = settled.filter(p => p.bttsCorrect !== null);
  const baseBttsRate = baseBtts.length ? baseBtts.filter(p => p.btts).length / baseBtts.length : 0.52;

  const rules = await Rule.find();
  for (const rule of rules) {
    if (!rule.key.startsWith('b')) continue;
    let triggers = 0, correct = 0;
    for (const s of settled) {
      triggers++;
      if (s.btts) correct++;
    }
    if (triggers < 15) continue;
    const hitRate = correct / triggers;
    const lift = hitRate - baseBttsRate;
    let weight = 1;
    if (lift >= 0.10) weight = 1.4;
    else if (lift >= 0.05) weight = 1.2;
    else if (lift >= 0.0) weight = 1.0;
    else if (lift >= -0.05) weight = 0.7;
    else if (lift >= -0.15) weight = 0.4;
    else weight = 0.1;
    await RulePerformance.updateOne(
      { ruleKey: rule.key },
      { $set: { totalTriggers: triggers, correctTriggers: correct, hitRate: +hitRate.toFixed(4), lift: +lift.toFixed(4), currentWeight: weight, muted: weight <= 0.1, lastEvaluated: new Date() } },
      { upsert: true }
    );
  }
  console.log('[Learning] Rule performance updated');
}

async function computeRollingStats() {
  const settled = await PredictionLog.find({ settledAt: { $ne: null }, bttsCorrect: { $ne: null } })
    .sort({ settledAt: -1 }).limit(100).lean();
  if (settled.length < 10) return;

  const elite = settled.filter(p => p.ourBttsProb >= 82);
  const strong = settled.filter(p => p.ourBttsProb >= 75 && p.ourBttsProb < 82);
  const value = settled.filter(p => p.ourBttsProb >= 68 && p.ourBttsProb < 75);
  const acc = settled.length ? +(settled.filter(p => p.bttsCorrect).length / settled.length * 100).toFixed(1) : 0;
  const eliteAcc = elite.length ? +(elite.filter(p => p.bttsCorrect).length / elite.length * 100).toFixed(1) : 0;
  const strongAcc = strong.length ? +(strong.filter(p => p.bttsCorrect).length / strong.length * 100).toFixed(1) : 0;
  const valueAcc = value.length ? +(value.filter(p => p.bttsCorrect).length / value.length * 100).toFixed(1) : 0;

  await new RollingStats({
    window: settled.length,
    bttsAcc: acc, eliteAcc, strongAcc, valueAcc,
    sampleSize: settled.length,
  }).save();
}

