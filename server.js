// BTTS PREDICTION ENGINE
// ═══════════════════════════════════════════════════════════
async function computeBttsPrediction(pred) {
  const cached = ENRICH_CACHE.get(pred.eventId);
  if (cached && Date.now() - cached.enrichedAt < ENV.ENRICH_CACHE_TTL) {
    Object.assign(pred, cached.pred);
    return pred;
  }

  const R = await getCachedRules();
  const [homeTH, awayTH, league, h2h, bookOdds] = await Promise.all([
    TeamHistory.findOne({ teamId: pred.homeTeam.id }).lean(),
    TeamHistory.findOne({ teamId: pred.awayTeam.id }).lean(),
    LeagueKnowledge.findOne({ leagueId: pred.leagueId }).lean(),
    H2H.findOne({ pairKey: [pred.homeTeam.id, pred.awayTeam.id].sort((a, b) => a - b).join('_') }).lean(),
    getBookmakerOddsFor(pred),
  ]);

  const useSplits = (homeTH?.homeAvgScored > 0) && (awayTH?.awayAvgScored > 0);

  const hAvgS = useSplits ? safeNum(homeTH.homeAvgScored, 1.4) : safeNum(homeTH?.avgScored, 1.2);
  const hAvgC = useSplits ? safeNum(homeTH.homeAvgConceded, 1.2) : safeNum(homeTH?.avgConceded, 1.2);
  const aAvgS = useSplits ? safeNum(awayTH.awayAvgScored, 1.0) : safeNum(awayTH?.avgScored, 1.2);
  const aAvgC = useSplits ? safeNum(awayTH.awayAvgConceded, 1.5) : safeNum(awayTH?.avgConceded, 1.2);

  const homeBtts = safeNum(homeTH?.bttsRate, 0.5);
  const awayBtts = safeNum(awayTH?.bttsRate, 0.5);

  const hasXG = (homeTH?.xgMatches || 0) >= 3 && (awayTH?.xgMatches || 0) >= 3;
  const hXG = safeNum(homeTH?.avgXG, hAvgS);
  const aXG = safeNum(awayTH?.avgXG, aAvgS);
  const hXGA = safeNum(homeTH?.avgXGA, hAvgC);
  const aXGA = safeNum(awayTH?.avgXGA, aAvgC);

  let lambdaHome, lambdaAway;
  if (hasXG) {
    lambdaHome = (hXG * 0.65 + hAvgS * 0.35) * 0.55 + (aXGA * 0.65 + aAvgC * 0.35) * 0.45;
    lambdaAway = (aXG * 0.65 + aAvgS * 0.35) * 0.55 + (hXGA * 0.65 + hAvgC * 0.35) * 0.45;
  } else {
    lambdaHome = (hAvgS * 0.6) + (aAvgC * 0.4);
    lambdaAway = (aAvgS * 0.6) + (hAvgC * 0.4);
  }

  if (pred.expectedHomeGoals != null && pred.expectedAwayGoals != null) {
    const bzHome = safeNum(pred.expectedHomeGoals, lambdaHome);
    const bzAway = safeNum(pred.expectedAwayGoals, lambdaAway);
    lambdaHome = lambdaHome * 0.65 + bzHome * 0.35;
    lambdaAway = lambdaAway * 0.65 + bzAway * 0.35;
  }

  const fatigueTh = R.b17_fatigue_penalty?.matchesThreshold || 3;
  const fatiguePen = R.b17_fatigue_penalty?.penalty || 0.06;
  if ((homeTH?.matchesLast7 || 0) >= fatigueTh) lambdaHome = Math.max(0.2, lambdaHome - fatiguePen * 2);
  if ((awayTH?.matchesLast7 || 0) >= fatigueTh) lambdaAway = Math.max(0.2, lambdaAway - fatiguePen * 2);

  if (!Number.isFinite(lambdaHome) || isNaN(lambdaHome)) lambdaHome = 1.2;
  if (!Number.isFinite(lambdaAway) || isNaN(lambdaAway)) lambdaAway = 1.2;

  const pHomeScores = 1 - Math.exp(-lambdaHome);
  const pAwayScores = 1 - Math.exp(-lambdaAway);
  let bttsProb = pHomeScores * pAwayScores;

  const histBtts = (homeBtts + awayBtts) / 2;
  const h2hBtts = safeNum(h2h?.bttsRate, histBtts);
  const blendedHist = histBtts * 0.55 + h2hBtts * 0.45;
  bttsProb = bttsProb * 0.55 + blendedHist * 0.45;

  const csTh = R.b14_clean_sheet_penalty?.highRate || 0.4;
  const csPen = R.b14_clean_sheet_penalty?.penalty || 0.10;
  if (safeNum(homeTH?.cleanSheetRate, 0) > csTh) bttsProb -= csPen;
  if (safeNum(awayTH?.cleanSheetRate, 0) > csTh) bttsProb -= csPen;

  const ftsTh = R.b15_fts_penalty?.highRate || 0.35;
  const ftsPen = R.b15_fts_penalty?.penalty || 0.12;
  if (safeNum(homeTH?.failedToScoreRate, 0) > ftsTh) bttsProb -= ftsPen;
  if (safeNum(awayTH?.failedToScoreRate, 0) > ftsTh) bttsProb -= ftsPen;

  if (league && league.totalMatches >= 10) {
    const lgBtts = safeNum(league.bttsHits / league.totalMatches, 0.5);
    const lgW = (R.b16_league_btts?.weight || 12) / 100;
    bttsProb = bttsProb * (1 - lgW) + lgBtts * lgW;
  }

  bttsProb = Math.max(0.05, Math.min(0.95, bttsProb));
  if (!Number.isFinite(bttsProb) || isNaN(bttsProb)) bttsProb = 0.5;

  const features = buildBttsFeatureVector(pred, homeTH, awayTH, league, h2h);
  const metaBtts = await metaPredictCached('btts', features);
  if (metaBtts !== null) bttsProb = bttsProb * 0.4 + metaBtts * 0.6;

  if (!Number.isFinite(bttsProb) || isNaN(bttsProb)) bttsProb = 0.5;

  bttsProb = await calibrateProbCached('btts', bttsProb);
  if (!Number.isFinite(bttsProb) || isNaN(bttsProb)) bttsProb = 0.5;

  const edgeDistance = Math.abs(bttsProb - 0.5) * 2;
  const hasEdge = edgeDistance >= ENV.EDGE_DISTANCE_MIN;

  const gate = R.b18_publish_gate || { elite: 0.82, strong: 0.75, value: 0.68 };
  let tier = bttsProb >= gate.elite ? 'elite'
           : bttsProb >= gate.strong ? 'strong'
           : bttsProb >= gate.value ? 'value'
           : bttsProb >= 0.55 ? 'speculative' : 'skip';

  if (!hasEdge) tier = 'skip';

  let qualityScore = Math.round(
    (bttsProb * 60) +
    (Math.min(hAvgS, 2.0) * 5) +
    (Math.min(aAvgS, 2.0) * 5) +
    (Math.min(hAvgC, 2.0) * 4) +
    (Math.min(aAvgC, 2.0) * 4) +
    (Math.min(homeBtts + awayBtts, 1.6) * 8) +
    ((homeTH?.xgMatches || 0) >= 5 ? 8 : 0) +
    ((awayTH?.xgMatches || 0) >= 5 ? 8 : 0)
  );
  if (!Number.isFinite(qualityScore) || isNaN(qualityScore)) qualityScore = 60;

  pred.bttsPick = {
    pick: bttsProb >= 0.5 ? 'Yes' : 'No',
    prob: +(bttsProb * 100).toFixed(1),
    confidence: bucketConfidence(bttsProb),
    tier, qualityScore,
    publishable: hasEdge && bttsProb >= gate.strong,
    lambdaHome: +lambdaHome.toFixed(2),
    lambdaAway: +lambdaAway.toFixed(2),
    hasXG, useSplits,
    reason: tier === 'elite' ? 'Elite BTTS — strong xG both sides'
          : tier === 'strong' ? 'Solid BTTS — good attacking data'
          : tier === 'value' ? 'Value BTTS'
          : tier === 'speculative' ? 'Speculative — higher risk'
          : !hasEdge ? 'Too close to 50/50 — skipped'
          : 'No BTTS edge',
  };

  pred.knowledge = {
    homeAttack: +hAvgS.toFixed(2),
    homeDefense: +hAvgC.toFixed(2),
    awayAttack: +aAvgS.toFixed(2),
    awayDefense: +aAvgC.toFixed(2),
    homeXG: hasXG ? +hXG.toFixed(2) : null,
    awayXG: hasXG ? +aXG.toFixed(2) : null,
    homeXGA: hasXG ? +hXGA.toFixed(2) : null,
    awayXGA: hasXG ? +aXGA.toFixed(2) : null,
    homeBttsRate: +homeBtts.toFixed(2),
    awayBttsRate: +awayBtts.toFixed(2),
    h2hBttsRate: h2h?.bttsRate || null,
    leagueBttsRate: league?.totalMatches >= 5 ? +(league.bttsHits / league.totalMatches).toFixed(3) : null,
    hasXG, useSplits,
    xgMatches: Math.min(homeTH?.xgMatches || 0, awayTH?.xgMatches || 0),
    homeForm: homeTH?.formLast5 || '',
    awayForm: awayTH?.formLast5 || '',
  };

  const book = bookOdds?.markets || {};
  const impliedBttsYes = +(100 / Math.max(1, pred.bttsPick.prob)).toFixed(2);
  const impliedBttsNo = +(100 / Math.max(1, 100 - pred.bttsPick.prob)).toFixed(2);

  pred.markets = {
    btts: {
      pick: pred.bttsPick.pick,
      probability: pred.bttsPick.prob,
      odds: book.btts?.yes || impliedBttsYes,
      oddsNo: book.btts?.no || impliedBttsNo,
      source: book.btts ? 'bookmaker' : 'implied',
    },
  };
  pred.bookmaker = bookOdds ? {
    key: bookOdds.bookmaker,
    title: bookOdds.bookmakerTitle,
    lastUpdated: bookOdds.lastUpdated,
  } : null;

  logFeatureSnapshot(pred, features, 'btts', bttsProb).catch(() => {});

  ENRICH_CACHE.set(pred.eventId, { enrichedAt: Date.now(), pred: JSON.parse(JSON.stringify(pred)) });
  if (ENRICH_CACHE.size > 500) {
    const now = Date.now();
    for (const [k, v] of ENRICH_CACHE) if (now - v.enrichedAt > ENV.ENRICH_CACHE_TTL) ENRICH_CACHE.delete(k);
  }
  return pred;
}

