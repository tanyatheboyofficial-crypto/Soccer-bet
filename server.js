async function activateSubscription(user, planKey) {
  const plan = PLANS[planKey];
  if (!plan) throw new Error('Invalid plan');
  const now = Date.now();
  const existing = user.vipExpiry && new Date(user.vipExpiry).getTime() > now ? new Date(user.vipExpiry).getTime() : now;
  user.accountType = 'vip';
  user.planKey = planKey;
  user.vipExpiry = new Date(existing + plan.days * 86400000);
  await user.save();
  if (user.referredBy) {
    const ref = await User.findOne({ username: user.referredBy });
    if (ref) {
      ref.subscribedReferrals = (ref.subscribedReferrals || 0) + 1;
      ref.betpulseCoins = (ref.betpulseCoins || 0) + 1;
      if (ref.subscribedReferrals % 10 === 0) ref.cashEarnedUSD = (ref.cashEarnedUSD || 0) + 2;
      await ref.save();
    }
  }
  return plan;
}

