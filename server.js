app.post('/api/admin/brain/import', auth, adminOnly, async (req, res) => {
  try {
    const brain = req.body;
    if (!brain || typeof brain !== 'object') return res.status(400).json({ error: 'Invalid brain file' });
    const mode = req.query.mode || 'merge';
    const stats = { rules: 0, rulePerformance: 0, calibration: 0, metaLearners: 0, teamHistory: 0, leagueKnowledge: 0, h2h: 0 };
    if (Array.isArray(brain.rules)) {
      if (mode === 'replace') await Rule.deleteMany({});
      for (const r of brain.rules) if (r.key && r.name) { await Rule.updateOne({ key: r.key }, { $set: r }, { upsert: true }); stats.rules++; }
    }
    if (Array.isArray(brain.rulePerformance)) {
      if (mode === 'replace') await RulePerformance.deleteMany({});
      for (const rp of brain.rulePerformance) if (rp.ruleKey) { await RulePerformance.updateOne({ ruleKey: rp.ruleKey }, { $set: rp }, { upsert: true }); stats.rulePerformance++; }
    }
    if (Array.isArray(brain.calibration)) {
      if (mode === 'replace') await Calibration.deleteMany({});
      for (const c of brain.calibration) if (c.market) { await Calibration.updateOne({ market: c.market }, { $set: c }, { upsert: true }); stats.calibration++; }
    }
    if (Array.isArray(brain.metaLearners)) {
      if (mode === 'replace') await MetaLearner.deleteMany({});
      for (const m of brain.metaLearners) if (m.market) { await MetaLearner.updateOne({ market: m.market }, { $set: m }, { upsert: true }); stats.metaLearners++; }
    }
    if (Array.isArray(brain.teamHistory)) {
      if (mode === 'replace') await TeamHistory.deleteMany({});
      for (const th of brain.teamHistory) if (th.teamId) { await TeamHistory.updateOne({ teamId: th.teamId }, { $set: th }, { upsert: true }); stats.teamHistory++; }
    }
    if (Array.isArray(brain.leagueKnowledge)) {
      if (mode === 'replace') await LeagueKnowledge.deleteMany({});
      for (const lk of brain.leagueKnowledge) if (lk.leagueId) { await LeagueKnowledge.updateOne({ leagueId: lk.leagueId }, { $set: lk }, { upsert: true }); stats.leagueKnowledge++; }
    }
    if (Array.isArray(brain.h2h)) {
      if (mode === 'replace') await H2H.deleteMany({});
      for (const h of brain.h2h) if (h.pairKey) { await H2H.updateOne({ pairKey: h.pairKey }, { $set: h }, { upsert: true }); stats.h2h++; }
    }
    invalidateCaches();
    res.json({ success: true, mode, imported: stats });
  } catch (e) { res.status(500).json({ error: e.message }); }
});

