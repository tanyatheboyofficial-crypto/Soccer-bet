function aggregateTeamHistory(team) {
  const m = team.matches || [];
  if (!m.length) return;
  const n = m.length;

  let scored = 0, conceded = 0, btts = 0, over15 = 0, over25 = 0, cs = 0, fts = 0;
  let homeScored = 0, homeConceded = 0, awayScored = 0, awayConceded = 0;
  let homeBtts = 0, awayBtts = 0, homeN = 0, awayN = 0;

  for (const x of m) {
    const gf = Number(x.goalsFor || 0);
    const ga = Number(x.goalsAgainst || 0);
    const total = gf + ga;
    scored += gf; conceded += ga;
    if (gf > 0 && ga > 0) btts++;
    if (total > 1.5) over15++;
    if (total > 2.5) over25++;
    if (ga === 0) cs++;
    if (gf === 0) fts++;

    if (x.homeOrAway === 'H') {
      homeScored += gf; homeConceded += ga;
      if (gf > 0 && ga > 0) homeBtts++;
      homeN++;
    } else {
      awayScored += gf; awayConceded += ga;
      if (gf > 0 && ga > 0) awayBtts++;
      awayN++;
    }
  }

  team.avgScored = +(scored / n).toFixed(2);
  team.avgConceded = +(conceded / n).toFixed(2);
  team.bttsRate = +(btts / n).toFixed(3);
  team.over15Rate = +(over15 / n).toFixed(3);
  team.over25Rate = +(over25 / n).toFixed(3);
  team.cleanSheetRate = +(cs / n).toFixed(3);
  team.failedToScoreRate = +(fts / n).toFixed(3);

  if (homeN > 0) {
    team.homeAvgScored = +(homeScored / homeN).toFixed(2);
    team.homeAvgConceded = +(homeConceded / homeN).toFixed(2);
    team.homeBttsRate = +(homeBtts / homeN).toFixed(3);
  }
  if (awayN > 0) {
    team.awayAvgScored = +(awayScored / awayN).toFixed(2);
    team.awayAvgConceded = +(awayConceded / awayN).toFixed(2);
    team.awayBttsRate = +(awayBtts / awayN).toFixed(3);
  }

  const sorted = [...m].sort((a, b) => new Date(b.date) - new Date(a.date));
  const last5 = sorted.slice(0, 5);
  let formString = '';
  let formPts = 0;
  for (const g of last5) {
    formString += g.result || '?';
    if (g.result === 'W') formPts += 3;
    else if (g.result === 'D') formPts += 1;
  }
  team.formLast5 = formString;
  team.formPointsLast5 = formPts;

  if (sorted[0]) team.restDays = Math.floor((Date.now() - new Date(sorted[0].date).getTime()) / 86400000);
  const sevenDaysAgo = Date.now() - 7 * 86400000;
  team.matchesLast7 = m.filter(x => new Date(x.date).getTime() > sevenDaysAgo).length;
  team.lastUpdated = new Date();
}

