async function bzGet(path, params = {}) {
  if (!BZZOIRO_KEY) throw new Error('BZZOIRO_API_KEY missing');
  const qs = new URLSearchParams(params).toString();
  const url = `${BZZOIRO_BASE}${path}${qs ? '?' + qs : ''}`;
  const res = await axios.get(url, {
    headers: { 'Authorization': `Token ${BZZOIRO_KEY}` },
    timeout: 20000,
  });
  return res.data;
}

